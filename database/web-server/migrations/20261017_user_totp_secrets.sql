-- Migration: server-only storage for 2FA (TOTP) secrets
-- Date: 2026-10-17
--
-- Why: the secret used to live in auth.users.app_metadata. Supabase embeds
-- app_metadata in every access token and returns it from /auth/v1/user, so any
-- stolen session also leaked the TOTP secret, defeating the second factor.
--
-- Access: RLS is enabled and NO policy is created, so only the service_role
-- (the web-server) can read or write. Ciphertexts are AES-256-GCM sealed by the
-- web-server with TOTP_ENCRYPTION_KEY; the database never sees a plaintext secret.

CREATE TABLE IF NOT EXISTS public.user_totp_secrets (
    user_id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    -- Active factor, promoted from pending once the user proves they scanned it.
    secret_ciphertext text,
    -- Generated by POST /api/auth/2fa/setup, consumed by POST /api/auth/2fa/enable.
    pending_secret_ciphertext text,
    -- Anti-replay: each TOTP time step is accepted at most once.
    last_used_step bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.user_totp_secrets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_totp_secrets FROM anon, authenticated;

COMMENT ON TABLE public.user_totp_secrets IS
    'Server-only TOTP secrets (service_role). Values are AES-256-GCM sealed by the web-server.';
